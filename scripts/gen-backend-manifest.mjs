#!/usr/bin/env node
/**
 * gen-backend-manifest.mjs -- write convex/lib/backendManifest.ts, the list of
 * PUBLIC Convex function identifiers this backend exposes, derived from the
 * source (scripts/lib/convex-public-functions.mjs).
 *
 *   node scripts/gen-backend-manifest.mjs          regenerate the file
 *   node scripts/gen-backend-manifest.mjs --check  exit 1 if it is stale
 *
 * Nothing is typed by hand. BACKEND_CONTRACT_VERSION is the one human-owned
 * value: the generator keeps whatever the file already carries (default 1).
 * Bump it by editing the file when the MCP starts passing a new argument to an
 * existing function (a name list cannot see that), together with
 * REQUIRED_CONTRACT_VERSION in mcp-server/src/backendContract.ts.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { listPublicConvexFunctions } from "./lib/convex-public-functions.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONVEX = join(ROOT, "convex");
const OUT = join(CONVEX, "lib", "backendManifest.ts");

function currentVersion() {
	if (!existsSync(OUT)) return 1;
	const m = /export const BACKEND_CONTRACT_VERSION = (\d+);/.exec(
		readFileSync(OUT, "utf8"),
	);
	return m ? Number(m[1]) : 1;
}

const functions = listPublicConvexFunctions(CONVEX);
if (functions.length === 0) {
	console.error("gen-backend-manifest: no public functions found -- refusing");
	process.exit(2);
}

const body = `// GENERATED by scripts/gen-backend-manifest.mjs -- do not edit by hand.
// Regenerate: node scripts/gen-backend-manifest.mjs
// Pinned by convex/__tests__/backendContract.test.ts: a public function added or
// removed without regenerating this file fails that test.
//
// BACKEND_CONTRACT_VERSION is the one hand-owned value. Bump it, together with
// REQUIRED_CONTRACT_VERSION in mcp-server/src/backendContract.ts, when the MCP
// starts passing a new argument to a function that already exists.

export const BACKEND_CONTRACT_VERSION = ${currentVersion()};

export const BACKEND_FUNCTIONS: readonly string[] = [
${functions.map((f) => `\t"${f}",`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
	const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
	if (have !== body) {
		console.error(
			"convex/lib/backendManifest.ts is stale -- run: node scripts/gen-backend-manifest.mjs",
		);
		process.exit(1);
	}
	console.log(`backendManifest.ts is current (${functions.length} functions)`);
} else {
	writeFileSync(OUT, body);
	console.log(`wrote ${OUT}: ${functions.length} functions`);
}
