/**
 * CLIENT SEAT MATRIX (VantagePeers Cloud, task k177e8dyrnykk3c56yf2b0pgfs8hhz06).
 *
 * Every tool the server lists on `tools/list`, called through the REAL /mcp route
 * by three seats with the plain arguments a client would send (no author, no
 * namespace unless the schema requires one), against the REAL Convex functions
 * (convex-test, reached as the fleet service account exactly as server-http.ts
 * reaches them). The world is test/lib/seatWorld.ts:
 *
 *   person-bound     a PERSON session (claude.ai: /authorize + consent + /token)
 *                    that chose its own personal agent at consent;
 *   person-agentless a PERSON session with no agent (the live case of the task:
 *                    immobiliere-pujol, whoami person-designates-no-agent);
 *   agent-seat       an AGENT seat token (a scope profile bound to one agent).
 *
 * Each cell is PASS / REFUSED(code) / ERROR (test/lib/seatMatrix.ts). Two
 * invariants tie the advertised text to what the server does:
 *   1. a person seat is never refused for want of an agent (PERSON_NO_HUMAN_DOOR,
 *      AGENT_CREDENTIAL_REQUIRED, ACTING_NAME_REQUIRED, CREATED_BY_REQUIRED) on a
 *      tool whose OWN text says a signed-in person may omit the author;
 *   2. a tool that refuses an agent-less person PERSON_NO_HUMAN_DOOR says so in
 *      its description (NO_PERSON_DOOR_NOTE, derived from its declaration).
 * With CLIENT_SEAT_MATRIX_OUT set, the matrix is written there as Markdown
 * (scripts/client-seat-matrix.mjs).
 */

import fs from "node:fs";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { NO_PERSON_DOOR_NOTE } from "../src/registerTool.js";
import {
	type Cell,
	classify,
	isPromisedButRefused,
	type ListedTool,
	plainArgs,
	renderMatrix,
	type SeatColumn,
} from "./lib/seatMatrix.js";
import {
	closeWorld,
	connectAs,
	freshBackend,
	SEATS,
	type Seat,
	type ToolResult,
	tokenFor,
} from "./lib/seatWorld.js";

vi.mock("convex/browser", async () => ({
	ConvexHttpClient: (await import("./lib/forwardingConvex.js"))
		.ForwardingConvexHttpClient,
}));

/** Destructive tools last, so a delete never removes the row a later call names. */
function callOrder(tools: ListedTool[]): ListedTool[] {
	const rank = (tool: ListedTool) =>
		tool.annotations?.destructiveHint === true
			? 2
			: tool.annotations?.readOnlyHint === true
				? 0
				: 1;
	return [...tools].sort((a, b) => rank(a) - rank(b));
}

async function runSeat(seat: Seat): Promise<{
	tools: ListedTool[];
	cells: Map<string, Cell>;
}> {
	const world = await freshBackend(seat);
	try {
		const client = await connectAs(await tokenFor(seat, world));
		const listed = (await client.listTools()).tools as ListedTool[];
		const cells = new Map<string, Cell>();
		for (const tool of callOrder(listed)) {
			let cell: Cell;
			try {
				const result = (await client.callTool({
					name: tool.name,
					arguments: plainArgs(tool, world.fixtures),
				})) as ToolResult;
				cell = classify(result);
			} catch (err: unknown) {
				cell = {
					kind: "ERROR",
					text: err instanceof Error ? err.message : String(err),
				};
			}
			cells.set(tool.name, cell);
		}
		await client.close();
		return { tools: listed, cells };
	} finally {
		closeWorld(world.harness);
	}
}

const columns: SeatColumn[] = [];
let tools: ListedTool[] = [];

beforeAll(() => {
	// No outbound network: an action that would fetch (embeddings, GitHub) fails fast.
	vi.stubGlobal(
		"fetch",
		async () => new Response("offline in the seat matrix", { status: 503 }),
	);
});

afterAll(() => {
	vi.unstubAllGlobals();
	const out = process.env.CLIENT_SEAT_MATRIX_OUT;
	if (out === undefined || out === "" || tools.length === 0) return;
	const title = process.env.CLIENT_SEAT_MATRIX_TITLE ?? "Client seat matrix";
	fs.writeFileSync(
		out,
		renderMatrix(
			title,
			[...tools].sort((a, b) => a.name.localeCompare(b.name)),
			columns,
			[
				"VantagePeers Cloud. Generated by `node scripts/client-seat-matrix.mjs` (mcp-server/test/client-seat-matrix.test.ts):",
				"every tool from `tools/list`, called through the real /mcp route with the plain arguments a client sends",
				"(no author, no namespace unless required), against the real Convex functions (convex-test).",
				"A cell marked **promised** is a person seat refused for want of an agent on a tool whose own text says a signed-in person may omit the author.",
				"",
				`Tools listed: ${tools.length}. Revision: ${process.env.CLIENT_SEAT_MATRIX_REV ?? "unknown"}.`,
			],
		),
	);
});

describe("client seat matrix: every listed tool, three seats, plain arguments", () => {
	for (const seat of SEATS) {
		it(`${seat}: the advertised text matches what the server does for this seat`, async () => {
			const run = await runSeat(seat);
			if (tools.length === 0) tools = run.tools;
			columns.push({ seat, cells: run.cells });
			expect(run.tools.length).toBeGreaterThan(50);
			const promisedButRefused = run.tools
				.filter((tool) => {
					const cell = run.cells.get(tool.name);
					return cell !== undefined && isPromisedButRefused(seat, tool, cell);
				})
				.map(
					(tool) => `${tool.name}: ${JSON.stringify(run.cells.get(tool.name))}`,
				);
			expect(promisedButRefused).toEqual([]);
			// A refusal for want of a person door is announced in the description.
			const unannounced = run.tools
				.filter((tool) => {
					const cell = run.cells.get(tool.name);
					return (
						seat === "person-agentless" &&
						cell?.kind === "REFUSED" &&
						cell.code === "PERSON_NO_HUMAN_DOOR" &&
						!(tool.description ?? "").includes(NO_PERSON_DOOR_NOTE)
					);
				})
				.map((tool) => tool.name);
			expect(unannounced).toEqual([]);
		}, 300_000);
	}
});
