import { ConvexError, v } from "convex/values";
import { internalMutation, internalQuery } from "./_generated/server";
import { clerkOrgIdForSlug } from "./lib/orgClerkId";
import { resolveProvisioningMapping } from "./lib/provisioningMapping";
import { requireAgentsOfOrg } from "./lib/rosterIds";

// ─────────────────────────────────────────────────────────────────────────────
// seedClientOrgMapping — idempotent per-org row provisioning.
// ─────────────────────────────────────────────────────────────────────────────
//
// Creates AT MOST ONE `client_org_mapping` document per Clerk org slug. The
// `_id` is generated by Convex on first insert and never re-created or
// re-typed — it is the durable address that `tenantSlug` (convex/lib/
// tenantSlug.ts) derives its neutral slug from.
//
// internalMutation: not client-facing. Only callable server-to-server (e.g.
// `npx convex run tenantOrgSeed:seedClientOrgMapping` by an operator, or from
// another internal function) — never exposed to the dashboard/MCP client
// surface. This is the auth boundary for this function: it is unreachable
// from any authenticated-but-untrusted client call.
//
// IDEMPOTENCE CONTRACT (load-bearing): calling this twice with the same
// `clerkOrgSlug` MUST NOT create a second document and MUST NOT change the
// existing document's `_id`. An `_id` that moves is an address that moves —
// a silent client outage the next time this seed is replayed.
//
// This function does NOT touch `memories`, namespaces, or
// `oauth_scope_profiles`. It only ensures the destination address exists.
// Migrating data to that address is a separate, later task.

export const seedClientOrgMapping = internalMutation({
	args: {
		clerkOrgSlug: v.string(),
		displayName: v.string(),
		allowedOrchestrators: v.array(v.string()),
		// The roster by agent ID (module M1): active agents of THIS org.
		allowedAgentIds: v.optional(v.array(v.id("agents"))),
		// The explicit fleet flag that replaces a "*" entry in the name roster.
		fleetWide: v.optional(v.boolean()),
		scopes: v.array(v.string()),
	},
	returns: v.id("client_org_mapping"),
	handler: async (ctx, args) => {
		const existing = await resolveProvisioningMapping(ctx, args.clerkOrgSlug);

		if (existing.kind === "row") {
			// Idempotent no-op: same _id, no second row, no mutation of fields.
			// (Field updates, if ever needed, are a distinct explicit mutation —
			// this seed's only job is "ensure the address exists exactly once".)
			return existing.row._id;
		}

		const allowedAgentIds =
			args.allowedAgentIds === undefined
				? undefined
				: await requireAgentsOfOrg(ctx, args.clerkOrgSlug, args.allowedAgentIds);
		return await ctx.db.insert("client_org_mapping", {
			clerkOrgSlug: args.clerkOrgSlug,
			displayName: args.displayName,
			allowedOrchestrators: args.allowedOrchestrators,
			...(allowedAgentIds !== undefined ? { allowedAgentIds } : {}),
			...(args.fleetWide === true ? { fleetWide: true } : {}),
			scopes: args.scopes,
			isActive: true,
			createdAt: Date.now(),
		});
	},
});

// ─────────────────────────────────────────────────────────────────────────────
// bindScopeProfileToOrg — the write half of the multi-tenant join.
// ─────────────────────────────────────────────────────────────────────────────
//
// `oauth_scope_profiles.clerkOrgSlug` is READ by the authorisation path
// (token mint copies it, `orgRoster:getForAccessToken` joins it to
// `client_org_mapping`) and was writable by nothing in production. This binds
// ONE profile to ONE organisation, mirroring `seedClientOrgMapping` above for
// the other side of the same join.
//
// internalMutation, same gating as the seed: unreachable from any client call.
// Operator command (DEV first, name the deployment from `<url>/instance_name`):
//   npx convex run tenantOrgSeed:bindScopeProfileToOrg \
//     '{"profileId":"<profileId>","clerkOrgSlug":"<org-slug>"}'
//
// Refusals — each its own code, never a shared one:
//   PROFILE_NOT_FOUND   no oauth_scope_profiles row for profileId
//   ORG_NOT_FOUND       no client_org_mapping row for clerkOrgSlug
//   ORG_INACTIVE        the mapping row exists with isActive === false
//   PROFILE_ALREADY_BOUND_ELSEWHERE  the profile is bound to a DIFFERENT org
//                       (moving a credential across tenants is not a seed's job)
//
// IDEMPOTENCE: same arguments twice returns the same `_id`, changes no row
// count, and does not touch `updatedAt` on the replay.

export const bindScopeProfileToOrg = internalMutation({
	args: { profileId: v.string(), clerkOrgSlug: v.string() },
	returns: v.id("oauth_scope_profiles"),
	handler: async (ctx, args) => {
		const profile = await ctx.db
			.query("oauth_scope_profiles")
			.withIndex("by_profileId", (q) => q.eq("profileId", args.profileId))
			.unique();
		if (!profile) {
			throw new ConvexError(
				`PROFILE_NOT_FOUND: no oauth_scope_profiles row for profileId "${args.profileId}"`,
			);
		}

		const provisioned = await resolveProvisioningMapping(ctx, args.clerkOrgSlug);
		const mapping = provisioned.kind === "row" ? provisioned.row : null;
		if (!mapping) {
			throw new ConvexError(
				`ORG_NOT_FOUND: no client_org_mapping row for clerkOrgSlug "${args.clerkOrgSlug}"`,
			);
		}
		if (!mapping.isActive) {
			throw new ConvexError(
				`ORG_INACTIVE: client_org_mapping for "${args.clerkOrgSlug}" exists but isActive is false`,
			);
		}

		if (profile.clerkOrgSlug === args.clerkOrgSlug) {
			return profile._id; // idempotent replay: no write
		}
		if (profile.clerkOrgSlug !== undefined && profile.clerkOrgSlug !== "") {
			throw new ConvexError(
				`PROFILE_ALREADY_BOUND_ELSEWHERE: profile "${args.profileId}" is bound to "${profile.clerkOrgSlug}", refusing to move it to "${args.clerkOrgSlug}"`,
			);
		}

		await ctx.db.patch(profile._id, {
			clerkOrgSlug: args.clerkOrgSlug,
			clerkOrgId: await clerkOrgIdForSlug(ctx, args.clerkOrgSlug),
			updatedAt: Date.now(),
		});
		return profile._id;
	},
});

// ─────────────────────────────────────────────────────────────────────────────
// moveScopeProfileToOrg — the deliberate, named move of a seat profile.
// ─────────────────────────────────────────────────────────────────────────────
//
// `bindScopeProfileToOrg` refuses PROFILE_ALREADY_BOUND_ELSEWHERE on purpose:
// moving a credential across tenants is not a seed's job. This is the separate,
// explicit operation for the case where an operator really means it (test seat
// profiles parked in probe orgs, relocated into one test org). Nothing is
// deleted: the profile row, its tokens and its agent all survive.
//
// internalMutation (admin credential only): unreachable from any client call.
// Operator command (name the deployment from `<url>/instance_name`):
//   npx convex run tenantOrgSeed:moveScopeProfileToOrg \
//     '{"profileId":"<id>","targetClerkOrgSlug":"<org-slug>",
//       "confirmProfileId":"<id>","reason":"<why, >= 10 chars>"}'
//
// Refusals — each its own code, each writes nothing:
//   PROFILE_NOT_FOUND            no oauth_scope_profiles row for profileId
//   ORG_NOT_FOUND                no client_org_mapping row for the target slug
//   ORG_INACTIVE                 the target mapping has isActive === false
//   OPERATOR_ORG_OUT_OF_SCOPE    the target is the operator's own org (orgKind "operator")
//   MOVE_NOT_NAMED               confirmProfileId !== profileId (the move names what it moves)
//   MOVE_REASON_REQUIRED         reason shorter than 10 characters once trimmed
//   TOKEN_SCAN_CAP_EXCEEDED      the profile has more tokens than one bounded scan can see
//
// A successful move: re-stamps clerkOrgSlug and clerkOrgId from the target,
// CLEARS agentId (the old agent belongs to the old org; re-bind afterwards with
// oauth:bindScopeProfileAgent), and revokes every live access and refresh token
// of the profile so no token keeps the old org. Both token tables are read
// through their `by_scopeProfile` index, bounded by MOVE_TOKEN_SCAN_CAP; a
// profile over the cap is REFUSED rather than decided on a partial view.
//
// IDEMPOTENCE: a profile already on the target slug returns moved:false with no
// write at all (updatedAt and tokens untouched).

const MOVE_TOKEN_SCAN_CAP = 2000;
const MOVE_REASON_MIN_LENGTH = 10;

export const moveScopeProfileToOrg = internalMutation({
	args: {
		profileId: v.string(),
		targetClerkOrgSlug: v.string(),
		confirmProfileId: v.string(),
		reason: v.string(),
	},
	returns: v.object({
		profileId: v.string(),
		previousOrgSlug: v.union(v.string(), v.null()),
		targetOrgSlug: v.string(),
		moved: v.boolean(),
		revokedAccessTokens: v.number(),
		revokedRefreshTokens: v.number(),
		previousAgentId: v.union(v.id("agents"), v.null()),
	}),
	handler: async (ctx, args) => {
		const profile = await ctx.db
			.query("oauth_scope_profiles")
			.withIndex("by_profileId", (q) => q.eq("profileId", args.profileId))
			.unique();
		if (!profile) {
			throw new ConvexError(
				`PROFILE_NOT_FOUND: no oauth_scope_profiles row for profileId "${args.profileId}"`,
			);
		}

		const provisioned = await resolveProvisioningMapping(ctx, args.targetClerkOrgSlug);
		const mapping = provisioned.kind === "row" ? provisioned.row : null;
		if (!mapping) {
			throw new ConvexError(
				`ORG_NOT_FOUND: no client_org_mapping row for clerkOrgSlug "${args.targetClerkOrgSlug}"`,
			);
		}
		if (!mapping.isActive) {
			throw new ConvexError(
				`ORG_INACTIVE: client_org_mapping for "${args.targetClerkOrgSlug}" exists but isActive is false`,
			);
		}
		if (mapping.orgKind === "operator") {
			throw new ConvexError(
				`OPERATOR_ORG_OUT_OF_SCOPE: "${args.targetClerkOrgSlug}" is the operator's own organisation, refusing to move a profile into it`,
			);
		}

		if (args.confirmProfileId !== args.profileId) {
			throw new ConvexError(
				`MOVE_NOT_NAMED: confirmProfileId must equal profileId "${args.profileId}" exactly`,
			);
		}
		if (args.reason.trim().length < MOVE_REASON_MIN_LENGTH) {
			throw new ConvexError(
				`MOVE_REASON_REQUIRED: reason must be at least ${MOVE_REASON_MIN_LENGTH} characters once trimmed`,
			);
		}

		const previousOrgSlug =
			profile.clerkOrgSlug !== undefined && profile.clerkOrgSlug !== ""
				? profile.clerkOrgSlug
				: null;

		if (profile.clerkOrgSlug === args.targetClerkOrgSlug) {
			return {
				profileId: args.profileId,
				previousOrgSlug,
				targetOrgSlug: args.targetClerkOrgSlug,
				moved: false,
				revokedAccessTokens: 0,
				revokedRefreshTokens: 0,
				previousAgentId: profile.agentId ?? null,
			};
		}

		// Read both token sets BEFORE any write: a refused scan must leave nothing behind.
		const accessTokens = await ctx.db
			.query("oauth_access_tokens")
			.withIndex("by_scopeProfile", (q) => q.eq("scopeProfile", args.profileId))
			.take(MOVE_TOKEN_SCAN_CAP + 1);
		const refreshTokens = await ctx.db
			.query("oauth_refresh_tokens")
			.withIndex("by_scopeProfile", (q) => q.eq("scopeProfile", args.profileId))
			.take(MOVE_TOKEN_SCAN_CAP + 1);
		if (accessTokens.length > MOVE_TOKEN_SCAN_CAP || refreshTokens.length > MOVE_TOKEN_SCAN_CAP) {
			throw new ConvexError(
				`TOKEN_SCAN_CAP_EXCEEDED: profile "${args.profileId}" has more than ${MOVE_TOKEN_SCAN_CAP} access or refresh tokens, refusing to decide on a partial view`,
			);
		}

		const now = Date.now();
		const liveAccess = accessTokens.filter((tok) => tok.revokedAt === undefined);
		const liveRefresh = refreshTokens.filter((tok) => tok.revokedAt === undefined);
		for (const tok of liveAccess) await ctx.db.patch(tok._id, { revokedAt: now });
		for (const tok of liveRefresh) await ctx.db.patch(tok._id, { revokedAt: now });

		await ctx.db.patch(profile._id, {
			clerkOrgSlug: args.targetClerkOrgSlug,
			clerkOrgId: await clerkOrgIdForSlug(ctx, args.targetClerkOrgSlug),
			agentId: undefined,
			updatedAt: now,
		});

		return {
			profileId: args.profileId,
			previousOrgSlug,
			targetOrgSlug: args.targetClerkOrgSlug,
			moved: true,
			revokedAccessTokens: liveAccess.length,
			revokedRefreshTokens: liveRefresh.length,
			previousAgentId: profile.agentId ?? null,
		};
	},
});

// ─────────────────────────────────────────────────────────────────────────────
// deriveRosterFromProfiles / setOrgRoster — roster correction.
// ─────────────────────────────────────────────────────────────────────────────
//
// The roster of an org is DERIVED from the `fromAllowList` of its profiles that
// still have at least one non-revoked `oauth_clients` row — never typed from a
// brief, never read off profile NAMES.
//
// THE UNION IS EXACT. No lowercasing, no accent folding, no deduplication by
// resemblance. Eta measured why on #1377: every consumer of this roster
// compares with `includes`, an EXACT match —
//   mcp-server/src/auth.ts:652   roster.includes(assignedTo)
//   convex/messages.ts:43
//   convex/tasks.ts:203
// so a roster folded to ["élan"] refuses a caller whose profile allows
// "elan" or "Elan". The first version of this function folded eight
// allowed spellings down to three, which reads as tidy and is a WITHHELD
// GRANT: the caller is refused on delegation and reads nothing on messages.
//
// A withheld grant is the direction nobody tests, because it surfaces as an
// empty list rather than as an error. Normalising a name before comparing it
// is the reflex, and a roster whose consumers use exact match is the one place
// that reflex is fatal. The same defect appeared independently in a roster
// written by hand for the same organisation, which is what proves it is a
// reflex and not a typing slip.
//
// So: whatever spelling a profile admits, this roster admits. Order is
// preserved and duplicates are removed only where the string is IDENTICAL.

export const deriveRosterFromProfiles = internalQuery({
	args: { profileIds: v.array(v.string()) },
	returns: v.object({
		roster: v.array(v.string()),
		activeProfiles: v.array(v.string()),
		skippedProfiles: v.array(v.string()),
	}),
	handler: async (ctx, args) => {
		const seen = new Set<string>();
		const roster: string[] = [];
		const activeProfiles: string[] = [];
		const skippedProfiles: string[] = [];
		for (const profileId of args.profileIds) {
			const profile = await ctx.db
				.query("oauth_scope_profiles")
				.withIndex("by_profileId", (q) => q.eq("profileId", profileId))
				.unique();
			const clients = await ctx.db
				.query("oauth_clients")
				.withIndex("by_scopeProfile", (q) => q.eq("scopeProfile", profileId))
				.collect();
			const hasActive = clients.some((c) => c.revokedAt === undefined);
			if (!profile || !hasActive) {
				skippedProfiles.push(profileId);
				continue;
			}
			activeProfiles.push(profileId);
			for (const name of profile.fromAllowList) {
				// Exact. A spelling the profile admits is a spelling the roster
				// admits — see the header for why folding is a withheld grant.
				if (seen.has(name)) continue;
				seen.add(name);
				roster.push(name);
			}
		}
		return {
			roster,
			activeProfiles,
			skippedProfiles,
		};
	},
});

export const setOrgRoster = internalMutation({
	args: {
		clerkOrgSlug: v.string(),
		allowedOrchestrators: v.array(v.string()),
		// The roster by agent ID (module M1): active agents of THIS org. When
		// given it replaces the stored ID roster; when absent it is untouched.
		allowedAgentIds: v.optional(v.array(v.id("agents"))),
	},
	returns: v.id("client_org_mapping"),
	handler: async (ctx, args) => {
		const provisioned = await resolveProvisioningMapping(ctx, args.clerkOrgSlug);
		const mapping = provisioned.kind === "row" ? provisioned.row : null;
		if (!mapping) {
			throw new ConvexError(
				`ORG_NOT_FOUND: no client_org_mapping row for clerkOrgSlug "${args.clerkOrgSlug}"`,
			);
		}
		const allowedAgentIds =
			args.allowedAgentIds === undefined
				? undefined
				: await requireAgentsOfOrg(ctx, args.clerkOrgSlug, args.allowedAgentIds);
		await ctx.db.patch(mapping._id, {
			allowedOrchestrators: args.allowedOrchestrators,
			...(allowedAgentIds !== undefined ? { allowedAgentIds } : {}),
		});
		return mapping._id;
	},
});
